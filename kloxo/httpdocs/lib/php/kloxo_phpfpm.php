<?php
declare(strict_types=1);

/**
 * Ubuntu PHP-FPM site pools: one pool per domain under /etc/php/X.Y/fpm/pool.d/,
 * socket /run/php/<domain>-phpX.Y.sock (never the unversioned php-fpm.sock symlink).
 * Render, php-fpmX.Y -t, atomic install, reload, roll back on failure.
 *
