 */

final class KloxoPhpfpmException extends RuntimeException
{
}

final class KloxoPhpfpm
{
    /** Tests point every absolute path under this directory. Never set from input. */
    public static string $fsPrefix = '';

    /** @var callable|null fn(list<string> $argv): array{code:int,out:string} */
    public static $runCmd = null;

    public static string $webGroup = 'www-data';

    public static function socketPath(string $phpId, string $user, string $domain = ''): string
    {
        $id = self::phpId($phpId);
        $series = self::seriesOf($id);
        if ($domain !== '') {
            $d = self::token($domain, true);
            if ($d === '' || $series === '') {
                throw new KloxoPhpfpmException('invalid domain or PHP version for socket');
            }

            return self::p('/run/php/' . $d . '-' . $id . '.sock');
        }
        $u = self::token($user !== '' ? $user : 'www-data');
        if ($u === '' || $id === '') {
            throw new KloxoPhpfpmException('invalid user or PHP version for socket');
        }

        return self::p('/run/php/' . $u . '-' . $id . '.sock');
    }

    /** Distro pool socket for this series. Never /run/php/php-fpm.sock. */
    public static function distroSocket(string $series): string
    {
        $s = self::seriesOf('php' . $series);
        if ($s === '') {
            $s = self::seriesOf($series);
        }
        if ($s === '') {
            throw new KloxoPhpfpmException('invalid PHP series for distro socket');
        }

        return self::p('/run/php/php' . $s . '-fpm.sock');
    }

    public static function poolFile(string $series, string $domain): string
    {
        $s = self::seriesOf('php' . $series) !== '' ? self::seriesOf('php' . $series) : self::seriesOf($series);
        $d = self::token($domain, true);
        if ($s === '' || $d === '') {
            throw new KloxoPhpfpmException('invalid pool path');
        }

        return self::p('/etc/php/' . $s . '/fpm/pool.d/kloxo-' . $d . '.conf');
    }

    public static function poolName(string $domain): string
    {
        $d = self::token($domain, true);
        $n = str_replace('.', '_', $d);

        return 'kloxo-' . $n;
    }

    /**
     * @param array<string,mixed> $flags php.ini-style pool overrides
     */
    public static function renderPool(string $domain, string $user, string $series, array $flags = []): string
    {
        $s = self::seriesOf('php' . $series) !== '' ? self::seriesOf('php' . $series) : self::seriesOf($series);
        $d = self::token($domain, true);
        $u = self::token($user);
        if ($s === '' || $d === '' || $u === '') {
            throw new KloxoPhpfpmException('invalid pool identity');
        }
        $id = 'php' . $s;
        $sock = self::socketPath($id, $u, $d);
        $name = self::poolName($d);
        $pm = self::pmMode(isset($flags['phpfpm_type_flag']) ? (string) $flags['phpfpm_type_flag'] : 'ondemand');
        $max = self::intFlag($flags['maxchildren'] ?? $flags['phpfcgiprocess_num'] ?? 6, 2, 256);
        $start = max(1, (int) floor($max / 3));
        $minSpare = max(1, (int) floor($max / 6));
        $maxSpare = max($minSpare, (int) floor($max / 3));
        $idle = '10s';
        $basedir = self::openBasedir($u, isset($flags['extrabasedir']) ? (string) $flags['extrabasedir'] : '');
        $errLog = self::p('/var/log/php/' . $d . '-php' . $s . '.log');
        $slow = self::p('/var/log/php/slow.log');
        $group = self::token(self::$webGroup) !== '' ? self::token(self::$webGroup) : 'www-data';
        $session = self::sessionPath($u, isset($flags['session_save_path_flag']) ? (string) $flags['session_save_path_flag'] : '');
        $ext = self::extList(isset($flags['phpfpm_limit_extensions']) ? (string) $flags['phpfpm_limit_extensions'] : '.php');

        $body = ';' . ' Generated by Kloxo CP. Do not edit; custom copies are backed up as .bak.*' . "\n"
            . '[' . $name . "]\n"
            . 'listen = ' . $sock . "\n"
            . "listen.owner = {$u}\n"
            . "listen.group = {$group}\n"
            . "listen.mode = 0660\n"
            . "user = {$u}\n"
            . "group = {$u}\n"
            . "pm = {$pm}\n"
            . "pm.max_children = {$max}\n"
            . "pm.start_servers = {$start}\n"
            . "pm.min_spare_servers = {$minSpare}\n"
            . "pm.max_spare_servers = {$maxSpare}\n"
            . "pm.process_idle_timeout = {$idle}\n"
            . "pm.max_requests = 1000\n"
            . "catch_workers_output = yes\n"
            . "security.limit_extensions = {$ext}\n"
            . 'php_admin_value[open_basedir] = ' . $basedir . "\n"
            . 'php_admin_value[error_log] = ' . $errLog . "\n"
            . "php_flag[log_errors] = on\n"
            . 'php_admin_value[session.save_path] = ' . $session . "\n"
            . "slowlog = {$slow}\n"
            . "request_slowlog_timeout = 30s\n";
        $admin = [
            'disable_functions' => 'disable_functions',
            'upload_max_filesize' => 'upload_max_filesize',
            'max_execution_time' => 'max_execution_time_flag',
            'max_input_time' => 'max_input_time_flag',
            'memory_limit' => 'memory_limit_flag',
            'post_max_size' => 'post_max_size_flag',
            'max_input_vars' => 'max_input_vars_flag',
            'date.timezone' => 'date_timezone_flag',
        ];
        foreach ($admin as $ini => $key) {
            if (!isset($flags[$key]) && !isset($flags[$ini])) {
                continue;
            }
            $v = (string) ($flags[$key] ?? $flags[$ini]);
            $v = self::iniValue($v);
            if ($v === '') {
                continue;
            }
            $body .= 'php_admin_value[' . $ini . '] = ' . $v . "\n";
        }
        $bools = [
            'display_errors' => 'display_error_flag',
            'file_uploads' => 'file_uploads_flag',
            'allow_url_fopen' => 'allow_url_fopen_flag',
            'allow_url_include' => 'allow_url_include_flag',
        ];
        foreach ($bools as $ini => $key) {
            if (!isset($flags[$key]) && !isset($flags[$ini])) {
                continue;
            }
            $on = self::flagOn($flags[$key] ?? $flags[$ini]);
            $body .= 'php_flag[' . $ini . '] = ' . ($on ? 'on' : 'off') . "\n";
        }

        return $body;
    }

    /**
     * Write the pool, validate php-fpmX.Y -t, reload. Previous file restored on failure.
     *
     * @param array<string,mixed> $flags
     */
    public static function installPool(string $domain, string $user, string $series, array $flags = []): void
    {
        $file = self::poolFile($series, $domain);
        $text = self::renderPool($domain, $user, $series, $flags);
        $dir = dirname($file);
        if (!is_dir($dir) && !@mkdir($dir, 0755, true) && !is_dir($dir)) {
            throw new KloxoPhpfpmException('cannot create ' . $dir);
        }
        $run = self::p('/run/php');
        if (!is_dir($run) && !@mkdir($run, 0755, true) && !is_dir($run)) {
            throw new KloxoPhpfpmException('cannot create ' . $run);
        }
        $logDir = self::p('/var/log/php');
        if (!is_dir($logDir)) {
            @mkdir($logDir, 0755, true);
        }
        $bak = null;
        if (is_file($file)) {
            $bak = $file . '.bak.' . gmdate('YmdHis') . '.' . getmypid();
            if (!@copy($file, $bak)) {
                throw new KloxoPhpfpmException('cannot backup ' . $file);
            }
        }
        self::atomicWrite($file, $text, 0640);
        try {
            self::validateFpm($series);
        } catch (Throwable $e) {
            if ($bak !== null && is_file($bak)) {
                @rename($bak, $file);
            } else {
                @unlink($file);
            }
            throw $e;
        }
    }

    public static function removePool(string $domain, string $series): void
    {
        $file = self::poolFile($series, $domain);
        if (!is_file($file)) {
            return;
        }
        $bak = $file . '.bak.' . gmdate('YmdHis') . '.' . getmypid();
        @copy($file, $bak);
        if (!@unlink($file)) {
            throw new KloxoPhpfpmException('cannot remove ' . $file);
        }
        try {
            self::validateFpm($series);
        } catch (Throwable $e) {
            if (is_file($bak)) {
                @rename($bak, $file);
            }
            throw $e;
        }
    }

    /**
     * Put this domain on $newSeries, drop its pool from every other series, reload both.
     *
     * @param array<string,mixed> $flags
     * @return list<string> series that were reloaded
     */
    public static function switchDomain(string $domain, string $user, string $newSeries, array $flags = []): array
    {
        $new = self::seriesOf('php' . $newSeries) !== '' ? self::seriesOf('php' . $newSeries) : self::seriesOf($newSeries);
        if ($new === '') {
            throw new KloxoPhpfpmException('invalid PHP series');
        }
        $old = self::domainSeries($domain);
        self::installPool($domain, $user, $new, $flags);
        foreach ($old as $s) {
            if ($s !== $new) {
                self::removePool($domain, $s);
            }
        }
        $touch = array_values(array_unique(array_merge($old, [$new])));
        foreach ($touch as $s) {
            self::reloadFpm($s);
        }
        self::syncUnits($touch);

        return $touch;
    }

    public static function removeDomain(string $domain): array
    {
        $old = self::domainSeries($domain);
        foreach ($old as $s) {
            self::removePool($domain, $s);
            self::reloadFpm($s);
        }
        if ($old !== []) {
            self::syncUnits($old);
        }

        return $old;
    }

    /**
     * Rewrite every pool that runs as this system user (PHP Configure).
     *
     * @param array<string,mixed> $flags
     */
    public static function refreshUserFlags(string $user, array $flags): void
    {
        $u = self::token($user);
        if ($u === '') {
            return;
        }
        $touched = [];
        foreach (self::allKloxoPools() as $row) {
            if ($row['user'] !== $u) {
                continue;
            }
            self::installPool($row['domain'], $u, $row['series'], $flags);
            $touched[$row['series']] = $row['series'];
        }
        foreach ($touched as $s) {
            self::reloadFpm($s);
        }
    }

    /** @return list<string> X.Y series that currently have a kloxo-*.conf for this domain */
    public static function domainSeries(string $domain): array
    {
        $d = self::token($domain, true);
        if ($d === '') {
            return [];
        }
        $out = [];
        $base = self::p('/etc/php');
        foreach (glob($base . '/*/fpm/pool.d/kloxo-' . $d . '.conf') ?: [] as $f) {
            if (!is_string($f)) {
                continue;
            }
            $series = basename(dirname($f, 3));
            if (preg_match('/^\d+\.\d+$/', $series) === 1) {
                $out[] = $series;
            }
        }

        return array_values(array_unique($out));
    }

    /**
     * Enable/start FPM for series in use; stop/disable installed series with no kloxo pools
     * (the distro www.conf pool does not keep a series "in use" for site PHP).
     *
     * @param list<string> $alsoKeep
     */
    public static function syncUnits(array $alsoKeep = []): void
    {
        include_once __DIR__ . '/kloxo_phpver.php';
        $keep = [];
        foreach ($alsoKeep as $s) {
            $v = self::seriesOf('php' . $s) !== '' ? self::seriesOf('php' . $s) : self::seriesOf((string) $s);
            if ($v !== '') {
                $keep[$v] = $v;
            }
        }
        foreach (self::allKloxoPools() as $row) {
            $keep[$row['series']] = $row['series'];
        }
        $act = KloxoPhpver::idToSeries(KloxoPhpver::activeId());
        if ($act !== '') {
            $keep[$act] = $act;
        }
        foreach (KloxoPhpver::installed() as $row) {
            if (($row['kind'] ?? '') !== 'distro') {
                continue;
            }
            $s = KloxoPhpver::idToSeries((string) ($row['id'] ?? ''));
            if ($s === '' || ($row['fpm'] ?? '') === '') {
                continue;
            }
            $unit = KloxoPhpver::fpmUnit('php' . $s);
            if ($unit === '') {
                continue;
            }
            if (isset($keep[$s])) {
                self::systemctl(['enable', '--now', $unit]);
            } else {
                self::systemctl(['disable', '--now', $unit]);
            }
        }
    }

    public static function validateFpm(string $series): void
    {
        include_once __DIR__ . '/kloxo_phpver.php';
        $s = self::seriesOf('php' . $series) !== '' ? self::seriesOf('php' . $series) : self::seriesOf($series);
        if ($s === '') {
            throw new KloxoPhpfpmException('invalid PHP series');
        }
        $bin = self::p(KloxoPhpver::fpmBin('php' . $s));
        if (self::$runCmd === null && ($bin === '' || !is_executable($bin))) {
            throw new KloxoPhpfpmException('php-fpm' . $s . ' is not installed');
        }
        $conf = self::p('/etc/php/' . $s . '/fpm/php-fpm.conf');
        $argv = [$bin !== '' ? $bin : 'php-fpm' . $s, '-t'];
        if (is_file($conf)) {
            $argv[] = '--fpm-config';
            $argv[] = $conf;
        }
        $r = self::run($argv);
        if ($r['code'] !== 0) {
            throw new KloxoPhpfpmException('php-fpm' . $s . ' -t failed: ' . self::oneLine($r['out']));
        }
    }

    public static function validateWeb(string $driver = 'nginx'): void
    {
        $d = strtolower(trim($driver));
        if ($d === 'none' || $d === '') {
            return;
        }
        if ($d === 'apache' || $d === 'apache2' || $d === 'httpd') {
            $apache = self::firstExec(['/usr/sbin/apache2ctl', '/usr/sbin/apachectl']);
            if ($apache === '') {
                return;
            }
            $r = self::run([$apache, 'configtest']);
            if ($r['code'] !== 0) {
                throw new KloxoPhpfpmException('apache configtest failed: ' . self::oneLine($r['out']));
            }

            return;
        }
        $nginx = self::firstExec(['/usr/sbin/nginx', '/usr/bin/nginx']);
        if ($nginx === '') {
            return;
        }
        $r = self::run([$nginx, '-t']);
        if ($r['code'] !== 0) {
            throw new KloxoPhpfpmException('nginx -t failed: ' . self::oneLine($r['out']));
        }
    }

    public static function reloadFpm(string $series): void
    {
        include_once __DIR__ . '/kloxo_phpver.php';
        $s = self::seriesOf('php' . $series) !== '' ? self::seriesOf('php' . $series) : self::seriesOf($series);
        if ($s === '') {
            return;
        }
        self::validateFpm($s);
        $unit = KloxoPhpver::fpmUnit('php' . $s);
        if ($unit === '') {
            return;
        }
        $r = self::systemctl(['reload', $unit]);
        if ($r['code'] !== 0) {
            $r = self::systemctl(['reload-or-restart', $unit]);
        }
        if ($r['code'] !== 0) {
            throw new KloxoPhpfpmException('could not reload ' . $unit . ': ' . self::oneLine($r['out']));
        }
    }

    /** Replace a bare `php` / `/usr/bin/php` cron command with the versioned CLI. */
    public static function rewriteCronPhp(string $command, string $cliBin): string
    {
        $cli = trim($cliBin);
        if ($cli === '' || strpbrk($cli, " \n\r\t") !== false) {
            return $command;
        }
        if (preg_match('/^php\d+\.\d+$/', basename($cli)) !== 1 && basename($cli) !== 'php') {
            if (!str_starts_with($cli, '/usr/bin/php')) {
                return $command;
            }
        }
        $out = preg_replace('#(?:^|(?<=\\s))/usr/bin/php(?!\\d)#', $cli, $command, 1);
        $command = is_string($out) ? $out : $command;
        if (preg_match('#(?:^|(?<=\\s))/usr/bin/php\\d#', $command) === 1) {
            return $command;
        }
        $out = preg_replace('/(?:^|(?<=\\s))php(?=\\s)/', $cli, $command, 1);

        return is_string($out) ? $out : $command;
    }

    public static function cronWrapper(string $domain, string $cliBin): string
    {
        $d = self::token($domain, true);
        $cli = trim($cliBin);
        if ($d === '' || $cli === '' || !str_starts_with($cli, '/usr/bin/php')) {
            throw new KloxoPhpfpmException('invalid cron wrapper');
        }
        $dir = self::p('/usr/local/bin');
        if (!is_dir($dir) && !@mkdir($dir, 0755, true) && !is_dir($dir)) {
            throw new KloxoPhpfpmException('cannot create ' . $dir);
        }
        $file = $dir . '/php-' . $d;
        $body = "#!/bin/sh\nexec " . escapeshellarg($cli) . " \"\$@\"\n";
        self::atomicWrite($file, $body, 0755);

        return $file;
    }

    // ------------------------------------------------------------------ internals

    private static function p(string $abs): string
    {
        if (self::$fsPrefix === '' || $abs === '') {
            return $abs;
        }

        return rtrim(self::$fsPrefix, '/') . $abs;
    }

    private static function phpId(string $id): string
    {
        $id = strtolower(trim($id));
        if ($id === '' || str_contains($id, 'php used') || str_starts_with($id, '--')) {
            include_once __DIR__ . '/kloxo_phpver.php';

            return KloxoPhpver::activeId();
        }
        if (preg_match('/^php\\d+\\.\\d+$/', $id) === 1) {
            return $id;
        }
        if (preg_match('/^\\d+\\.\\d+$/', $id) === 1) {
            return 'php' . $id;
        }

        return $id;
    }

    private static function seriesOf(string $id): string
    {
        if (preg_match('/^php(\\d+\\.\\d+)$/', $id, $m) === 1) {
            return $m[1];
        }
        if (preg_match('/^\\d+\\.\\d+$/', $id) === 1) {
            return $id;
        }

        return '';
    }

    private static function token(string $s, bool $allowDot = false): string
    {
        $s = strtolower(trim($s));
        $pat = $allowDot ? '/[^a-z0-9._-]+/' : '/[^a-z0-9_-]+/';
        $s = (string) preg_replace($pat, '', $s);
        if ($s === '' || str_contains($s, '..') || strlen($s) > 253) {
            return '';
        }

        return $s;
    }

    private static function pmMode(string $pm): string
    {
        $pm = strtolower(trim($pm));

        return in_array($pm, ['ondemand', 'dynamic', 'static'], true) ? $pm : 'ondemand';
    }

    private static function intFlag(mixed $v, int $min, int $max): int
    {
        $n = is_numeric($v) ? (int) $v : $min;
        if ($n < $min) {
            return $min;
        }
        if ($n > $max) {
            return $max;
        }

        return $n;
    }

    private static function openBasedir(string $user, string $extra): string
    {
        $extra = str_replace(["\0", "\n", "\r"], '', $extra);
        $parts = ['/home/' . $user . '/', '/tmp/', '/usr/share/pear/', '/home/kloxo/httpd/script/', '/home/kloxo/httpd/disable/'];
        if ($extra !== '') {
            foreach (explode(':', $extra) as $p) {
                $p = trim($p);
                if ($p !== '' && str_starts_with($p, '/') && !str_contains($p, '..')) {
                    $parts[] = $p;
                }
            }
        }

        return implode(':', array_unique($parts));
    }

    private static function sessionPath(string $user, string $given): string
    {
        $given = str_replace(["\0", "\n", "\r"], '', $given);
        if ($given !== '' && str_starts_with($given, '/') && !str_contains($given, '..')) {
            return $given;
        }

        return '/home/' . $user . '/__session';
    }

    private static function extList(string $raw): string
    {
        $out = [];
        foreach (preg_split('/\\s+/', strtolower($raw)) ?: [] as $e) {
            $e = ltrim($e, '.');
            if (preg_match('/^[a-z0-9]+$/', $e) === 1) {
                $out[] = '.' . $e;
            }
        }

        return $out !== [] ? implode(' ', $out) : '.php';
    }

    private static function iniValue(string $v): string
    {
        $v = str_replace(["\0", "\n", "\r", ';', '"'], '', $v);
        $v = trim($v);
        if (strlen($v) > 200) {
            return '';
        }

        return $v;
    }

    private static function flagOn(mixed $v): bool
    {
        $s = strtolower(trim((string) $v));

        return in_array($s, ['on', '1', 'true', 'yes'], true);
    }

    /**
     * @return list<array{domain:string,series:string,user:string,file:string}>
     */
    private static function allKloxoPools(): array
    {
        $out = [];
        foreach (glob(self::p('/etc/php') . '/*/fpm/pool.d/kloxo-*.conf') ?: [] as $f) {
            if (!is_string($f) || !is_file($f)) {
                continue;
            }
            $series = basename(dirname($f, 3));
            if (preg_match('/^\\d+\\.\\d+$/', $series) !== 1) {
                continue;
            }
            $base = basename($f, '.conf');
            if (!str_starts_with($base, 'kloxo-')) {
                continue;
            }
            $domain = substr($base, 6);
            $user = '';
            foreach (file($f, FILE_IGNORE_NEW_LINES) ?: [] as $line) {
                if (preg_match('/^user\\s*=\\s*(\\S+)/', $line, $m) === 1) {
                    $user = self::token($m[1]);
                    break;
                }
            }
            $out[] = ['domain' => $domain, 'series' => $series, 'user' => $user, 'file' => $f];
        }

        return $out;
    }

    private static function atomicWrite(string $file, string $text, int $mode): void
    {
        $dir = dirname($file);
        if (!is_dir($dir) && !@mkdir($dir, 0755, true) && !is_dir($dir)) {
            throw new KloxoPhpfpmException('cannot create ' . $dir);
        }
        $tmp = $file . '.new.' . getmypid();
        if (@file_put_contents($tmp, $text) === false) {
            throw new KloxoPhpfpmException('cannot write ' . $tmp);
        }
        @chmod($tmp, $mode);
        if (!@rename($tmp, $file)) {
            @unlink($tmp);
            throw new KloxoPhpfpmException('cannot install ' . $file);
        }
    }

    /** @param list<string> $argv */
    private static function run(array $argv): array
    {
        if (self::$runCmd !== null) {
            $r = (self::$runCmd)($argv);

            return ['code' => (int) ($r['code'] ?? 1), 'out' => (string) ($r['out'] ?? '')];
        }
        if ($argv === [] || !is_string($argv[0]) || $argv[0] === '') {
            return ['code' => 127, 'out' => 'empty command'];
        }
        $bin = $argv[0];
        if ($bin[0] !== '/' || !is_executable($bin)) {
            return ['code' => 127, 'out' => 'not executable: ' . $bin];
        }
        $p = @proc_open($argv, [
            0 => ['file', '/dev/null', 'r'],
            1 => ['pipe', 'w'],
            2 => ['pipe', 'w'],
        ], $pipes);
        if (!is_resource($p)) {
            return ['code' => 127, 'out' => 'could not start ' . $bin];
        }
        $out = (string) stream_get_contents($pipes[1]);
        $err = (string) stream_get_contents($pipes[2]);
        fclose($pipes[1]);
        fclose($pipes[2]);

        return ['code' => proc_close($p), 'out' => trim($out . "\n" . $err)];
    }

    /** @param list<string> $args */
    private static function systemctl(array $args): array
    {
        $bin = self::firstExec(['/usr/bin/systemctl', '/bin/systemctl']);
        if ($bin === '' && self::$runCmd === null) {
            return ['code' => 127, 'out' => 'systemctl not found'];
        }

        return self::run(array_merge([$bin !== '' ? $bin : 'systemctl'], $args));
    }

    /** @param list<string> $cands */
    private static function firstExec(array $cands): string
    {
        foreach ($cands as $c) {
            $p = self::p($c);
            if (is_executable($p)) {
                return $p;
            }
        }

        return '';
    }

    private static function oneLine(string $s): string
    {
        $s = preg_replace('/[^\x20-\x7e]/', ' ', $s) ?? '';
        $s = trim(preg_replace('/\\s+/', ' ', $s) ?? $s);

        return substr($s, 0, 240);
    }
